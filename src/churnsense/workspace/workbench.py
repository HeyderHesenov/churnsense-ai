"""Customer Intelligence and the Retention Workbench, without the HTTP.

Each request builds what it needs from the synthetic dataset and throws it away:
``load_book`` generates every account once and assesses its latest snapshot, and
the list and the summary are read from that one book; ``account_detail``
generates the one account it is asked for. Nothing is cached, stored or shared
between requests, and nothing here reads the Data Hub's uploads - the preview
keeps none.

Every business number a page shows is computed here, never in a browser.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import date
from typing import Final

from churnsense.exceptions import SchemaValidationError
from churnsense.workspace import contract, portfolio, risk, synthetic
from churnsense.workspace import workbench_schemas as out
from churnsense.workspace.schemas import AccountStatus
from churnsense.workspace.snapshot import Snapshot

#: Where a level stands in the default order; an account not assessed comes last.
LEVEL_RANK: Final[dict[str | None, int]] = {"attention": 0, "watch": 1, "no_signals": 2, None: 3}
MAX_PAGE_SIZE: Final = 100
DEFAULT_PAGE_SIZE: Final = 25

NOTE_SYNTHETIC = (
    "Synthetic preview data: every account is generated by ChurnSense from a fixed seed. No "
    "account is real, and nothing here is evidence of model performance or business outcomes."
)
NOTE_RULES = (
    f"Assessed by transparent rules ({risk.METHOD_VERSION}), not by a model: there is no "
    "probability. The thresholds are initial operational heuristics, not validated against "
    "real churn outcomes, and a signal identifies no cause of churn."
)
NOTE_NOT_ASSESSED = (
    "Trialing, paused and canceled accounts are not assessed: the rules apply to accounts "
    "with an active paid subscription, so these are not accounts without risk."
)
NOTE_CURRENCY = portfolio.CURRENCY_DEFINITION
NOTE_STATELESS = (
    "Nothing is stored: the dataset is generated for each request. Accounts uploaded to the "
    "Data Hub preview are not kept and do not appear here."
)


@dataclass(frozen=True, slots=True)
class Entry:
    """One account as the list sees it: its latest snapshot and that snapshot's assessment."""

    latest: Snapshot
    assessment: risk.Assessment

    @property
    def days_to_renewal(self) -> int | None:
        return risk.days_to_renewal(self.latest)


@dataclass(frozen=True, slots=True)
class Book:
    """The request's dataset: every account's latest assessment, in ID order."""

    dataset: out.DatasetInfo
    entries: tuple[Entry, ...]


def dataset_info(
    accounts: int = synthetic.DEFAULT_ACCOUNTS,
    seed: int = synthetic.DEFAULT_SEED,
    as_of: date = synthetic.DEFAULT_AS_OF,
) -> out.DatasetInfo:
    return out.DatasetInfo(
        generator_version=synthetic.GENERATOR_VERSION,
        seed=seed,
        accounts=accounts,
        as_of_date=as_of,
        snapshots_per_account=synthetic.SNAPSHOTS,
        snapshot_interval_days=synthetic.INTERVAL_DAYS,
    )


def build_book(accounts: Iterable[synthetic.Account], dataset: out.DatasetInfo) -> Book:
    """Each account's latest snapshot assessed with its earlier ones."""
    return Book(
        dataset=dataset,
        entries=tuple(Entry(a.latest, risk.assess(a.latest, a.snapshots[:-1])) for a in accounts),
    )


def load_book(
    accounts: int = synthetic.DEFAULT_ACCOUNTS,
    seed: int = synthetic.DEFAULT_SEED,
    as_of: date = synthetic.DEFAULT_AS_OF,
) -> Book:
    """The default synthetic dataset, generated once for this request."""
    return build_book(
        synthetic.iter_accounts(accounts, seed=seed, as_of=as_of),
        dataset_info(accounts, seed, as_of),
    )


# --- to the response ---------------------------------------------------------------------------


def snapshot_record(s: Snapshot) -> out.SnapshotRecord:
    return out.SnapshotRecord(**s.as_dict())


def assessment_out(a: risk.Assessment) -> out.Assessment:
    return out.Assessment(
        method=a.method,
        method_version=a.method_version,
        as_of_date=a.as_of_date,
        eligibility="assessed" if a.assessed else "not_assessed",
        level=a.level,
        not_assessed_reason=a.not_assessed_reason,
        indicators=[
            out.Indicator(
                code=i.code,
                severity=i.severity,
                title=i.title,
                explanation=i.explanation,
                observed=i.observed,
                unit=i.unit,
                rule=i.rule,
                observed_on=i.observed_on,
                compared_with=i.compared_with,
                evidence=[
                    out.EvidenceValue(field=e.field, as_of_date=e.as_of_date, value=e.value)
                    for e in i.evidence
                ],
            )
            for i in a.indicators
        ],
        rules_not_applied=[out.RuleNotApplied(rule=r.rule, reason=r.reason) for r in a.skipped],
        trend_compared_with=a.trend_baseline,
    )


def _focus(i: risk.Indicator) -> str:
    match i.code:
        case "payment_past_due":
            return "Check the overdue payment with billing."
        case "renewal_due":
            return f"Prepare for the renewal on {i.evidence[0].value}."
        case "inactivity":
            return f"Find out why no user has been active since {i.evidence[0].value}."
        case "sessions_decline" | "key_actions_decline":
            return f"Review the fall in {risk.TREND_METRICS[i.evidence[0].field]} with the account."
        case "low_active_user_coverage":
            return "Review adoption: few purchased seats have an active user."
    raise ValueError(f"no focus for {i.code!r}")


def next_step_context(a: risk.Assessment) -> str:
    """Where the evidence points the team first: the leading signal's focus, nothing more.

    It names what to look at, never an offer or an intervention: no rule here
    has evidence that any particular action works.
    """
    if not a.assessed:
        return f"No review indicated by these rules: the account is {a.status}."
    if not a.indicators:
        return "No rule signal: nothing in this account's latest data meets a rule threshold."
    lead, others = a.indicators[0], len(a.indicators) - 1
    more = "" if others == 0 else f" {others} more signal{'s' if others > 1 else ''} listed."
    return f"{lead.severity.capitalize()}: {_focus(lead)}{more}"


def account_row(e: Entry) -> out.AccountRow:
    s = e.latest
    return out.AccountRow(
        account_id=s.account_external_id,
        account_name=s.account_name,
        status=s.status,
        segment=s.segment,
        company_size_band=s.company_size_band,
        industry=s.industry,
        currency=s.currency,
        mrr=s.mrr,
        renewal_date=s.renewal_date,
        days_to_renewal=e.days_to_renewal,
        assessment=assessment_out(e.assessment),
        next_step_context=next_step_context(e.assessment),
    )


# --- the Workbench list ------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Filters:
    level: tuple[str, ...] = ()
    status: tuple[str, ...] = ()
    currency: str | None = None
    segment: str | None = None
    renewal_within_days: int | None = None
    q: str | None = None

    def matches(self, e: Entry) -> bool:
        s, a = e.latest, e.assessment
        if self.level and (a.level or "not_assessed") not in self.level:
            return False
        if self.status and s.status not in self.status:
            return False
        if self.currency is not None and s.currency != self.currency:
            return False
        if self.segment is not None and s.segment != self.segment:
            return False
        if self.renewal_within_days is not None:
            days = e.days_to_renewal
            if days is None or days > self.renewal_within_days:
                return False
        if self.q is not None:
            needle = self.q.casefold()
            if needle not in s.account_external_id.casefold() and (
                s.account_name is None or needle not in s.account_name.casefold()
            ):
                return False
        return True


def _ordered(entries: Sequence[Entry], sort: out.SortKey) -> list[Entry]:
    match sort:
        case "priority":
            # Attention, watch, no signals, not assessed; the nearest renewal first within a
            # level (none last); the account ID breaks every tie.
            return sorted(
                entries,
                key=lambda e: (
                    LEVEL_RANK[e.assessment.level],
                    e.days_to_renewal is None,
                    e.days_to_renewal or 0,
                    e.latest.account_external_id,
                ),
            )
        case "renewal_asc":
            return sorted(
                entries,
                key=lambda e: (
                    e.days_to_renewal is None,
                    e.days_to_renewal or 0,
                    e.latest.account_external_id,
                ),
            )
        case "mrr_desc":
            if len({e.latest.currency for e in entries}) > 1:
                raise AssertionError("mrr_desc is only ever sorted within one currency")
            return sorted(entries, key=lambda e: (-e.latest.mrr, e.latest.account_external_id))
    raise ValueError(f"no sort {sort!r}")


def account_page(
    book: Book, filters: Filters, sort: out.SortKey, page: int, page_size: int
) -> out.AccountPage:
    """One page of the matching accounts in ``sort`` order; a page past the end is the last."""
    if sort == "mrr_desc" and filters.currency is None:
        raise SchemaValidationError(
            "sort=mrr_desc compares amounts, so it needs a currency filter: amounts in "
            "different currencies are not comparable"
        )
    if not 1 <= page_size <= MAX_PAGE_SIZE:
        raise SchemaValidationError(f"page_size must be from 1 to {MAX_PAGE_SIZE}")
    matches = _ordered([e for e in book.entries if filters.matches(e)], sort)
    pages = max(1, -(-len(matches) // page_size))
    page = min(max(1, page), pages)
    return out.AccountPage(
        dataset=book.dataset,
        total=len(matches),
        page=page,
        page_size=page_size,
        pages=pages,
        sort=sort,
        filters=out.AppliedFilters(
            level=list(filters.level),
            status=list(filters.status),
            currency=filters.currency,
            segment=filters.segment,
            renewal_within_days=filters.renewal_within_days,
            q=filters.q,
        ),
        rows=[account_row(e) for e in matches[(page - 1) * page_size : page * page_size]],
        notes=[NOTE_SYNTHETIC, NOTE_RULES, NOTE_NOT_ASSESSED, NOTE_CURRENCY],
    )


# --- one account -------------------------------------------------------------------------------


def account_detail(account: synthetic.Account, dataset: out.DatasetInfo) -> out.AccountDetail:
    """The account's latest snapshot and assessment, and each snapshot assessed as it stood."""
    history = risk.assess_history(account.snapshots)
    latest, current = account.latest, history[-1]
    tenure = (
        (latest.as_of_date - latest.customer_since).days
        if latest.customer_since is not None
        else None
    )
    return out.AccountDetail(
        dataset=dataset,
        account_id=account.account_id,
        account_name=latest.account_name,
        latest=snapshot_record(latest),
        subscription=out.Subscription(
            status=latest.status,
            mrr=latest.mrr,
            currency=latest.currency,
            customer_since=latest.customer_since,
            tenure_days=tenure,
            renewal_date=latest.renewal_date,
            days_to_renewal=risk.days_to_renewal(latest),
            canceled_at=latest.canceled_at,
            cancellation_reason=latest.cancellation_reason,
        ),
        assessment=assessment_out(current),
        next_step_context=next_step_context(current),
        history=[
            out.HistoryEntry(snapshot=snapshot_record(s), assessment=assessment_out(a))
            for s, a in zip(account.snapshots, history, strict=True)
        ],
        notes=[NOTE_SYNTHETIC, NOTE_RULES, NOTE_STATELESS],
    )


# --- the portfolio -----------------------------------------------------------------------------


def portfolio_summary(book: Book) -> out.PortfolioSummary:
    """Counts across the book, and amounts per currency - never one total of two currencies."""
    entries = book.entries
    levels = Counter(e.assessment.level for e in entries if e.assessment.assessed)
    excluded = Counter(e.latest.status for e in entries if not e.assessment.assessed)
    eligible = sum(levels.values())
    rules = risk.RULES
    windows = (
        (0, rules.renewal_attention_days, "attention"),
        (rules.renewal_attention_days + 1, rules.renewal_watch_days, "watch"),
    )
    # Only an assessed account has a days_to_renewal (risk.days_to_renewal).
    renewing = [e.days_to_renewal for e in entries]
    return out.PortfolioSummary(
        dataset=book.dataset,
        total_accounts=len(entries),
        eligible_accounts=eligible,
        excluded_accounts=len(entries) - eligible,
        not_assessed=out.NotAssessedCounts(
            trialing=excluded["trialing"], paused=excluded["paused"], canceled=excluded["canceled"]
        ),
        levels=out.LevelCounts(
            attention=levels["attention"], watch=levels["watch"], no_signals=levels["no_signals"]
        ),
        currencies=[
            out.CurrencySummary(
                currency=t.currency,
                accounts=t.accounts,
                eligible_accounts=t.eligible,
                excluded_accounts=t.excluded,
                levels=out.LevelCounts(
                    attention=t.levels["attention"],
                    watch=t.levels["watch"],
                    no_signals=t.levels["no_signals"],
                ),
                active_mrr=t.active_mrr,
                attention_mrr=t.attention_mrr,
                watch_mrr=t.watch_mrr,
                no_signals_mrr=t.no_signals_mrr,
                exposed_mrr=t.exposed_mrr,
            )
            for t in portfolio.by_currency((e.latest, e.assessment) for e in entries)
        ],
        renewals=[
            out.RenewalWindow(
                from_days=low,
                to_days=high,
                severity=severity,
                accounts=sum(1 for d in renewing if d is not None and low <= d <= high),
            )
            for low, high, severity in windows
        ],
        methodology=out.Methodology(
            method=risk.METHOD,
            method_version=risk.METHOD_VERSION,
            rules=[
                out.RuleDescription(code=code, rule=text) for code, text in rules.describe().items()
            ],
            statement=NOTE_RULES,
        ),
        definitions={
            "active_mrr": portfolio.ACTIVE_MRR_DEFINITION,
            "exposed_mrr": portfolio.EXPOSED_MRR_DEFINITION,
            "currency": portfolio.CURRENCY_DEFINITION,
        },
        notes=[NOTE_SYNTHETIC, NOTE_NOT_ASSESSED, NOTE_STATELESS],
    )


def status_filter(values: Iterable[AccountStatus]) -> tuple[str, ...]:
    """Requested statuses, each once, in the contract's order."""
    wanted = set(values)
    return tuple(s for s in contract.STATUSES if s in wanted)


def level_filter(values: Iterable[out.LevelFilter]) -> tuple[str, ...]:
    """Requested levels, each once, in priority order."""
    wanted = set(values)
    return tuple(v for v in ("attention", "watch", "no_signals", "not_assessed") if v in wanted)
