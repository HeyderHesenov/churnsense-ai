type Method = 'get' | 'post';
type V2Path = keyof paths;
type Success<P extends V2Path, M extends Method> = paths[P][M] extends {
  responses: { 200: { content: { 'application/json': infer Body } } };
}
  ? Body
  : never;

function route(path: V2Path): string {
  return path.replace(/\{(\w+)\}/g, ':$1');
}

/** ``method path`` answered by ``resolve``, which reads the request. */
export function v2Respond<P extends V2Path, M extends Method>(
  method: M,
  path: P,
  resolve: (request: Request) => Success<P, M> | Promise<Success<P, M>>,
) {
  return http[method](route(path), async ({ request }) =>
    HttpResponse.json((await resolve(request)) as JsonBodyType),
  );
}

/** ``method path`` answered with ``body``. */
export function v2Answer<P extends V2Path, M extends Method>(
  method: M,
  path: P,
  body: Success<P, M>,
) {
  return v2Respond(method, path, () => body);
}

/** ``method path`` refused with ``status``, in the API's error shape. */
export function v2Refuse(
  method: Method,
  path: V2Path,
  status: number,
  error: string,
  problems: string[] = [],
) {
  const body: components['schemas']['ErrorResponse'] = {
    error,
    detail: 'Refused by a test.',
    problems,
  };
  return http[method](route(path), () => HttpResponse.json(body, { status }));
}

